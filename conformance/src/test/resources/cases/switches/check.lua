local Switches = require("src/switches")

assert(Switches.describe(1) == "one")
assert(Switches.describe(3) == "a few")
assert(Switches.describe(9) == "many")
assert(Switches.weight("small") == 1)
assert(Switches.weight("large") == 5)
assert(Switches.weight("tiny") == -1)
assert(Switches.isWeekend("sun") and not Switches.isWeekend("mon"))
assert(Switches.amount({}) == "none")
assert(Switches.amount({ 7 }) == "one")
assert(Switches.amount({ 7, 8 }) == "several")
assert(Switches.parity(4) == "even")
assert(Switches.parity(-3) == "odd", "Java's % keeps the sign")
assert(Switches.price("apple", false) == 3)
assert(Switches.price("pear", true) == 3)
assert(Switches.price("pear", false) == 4)
assert(Switches.price("plum", true) == 0)
assert(Switches.season(1) == "winter" and Switches.season(7) == "summer" and Switches.season(10) == "autumn")
assert(Switches.label(5) == "poor")
assert(Switches.label(2) == "level 2")
assert(Switches.sumOdd({ 1, 2, 3, 4, 5 }) == 9)
assert(Switches.bonus(1) == 0 and Switches.bonus(2) == 5 and Switches.bonus(3) == 0)
