local Expressions = require("src/expressions")

local integers = Expressions.integers()
assert(integers[4] == 255 and integers[5] == 5 and integers[6] == 15 and integers[7] == -7)
local decimals = Expressions.decimals()
assert(decimals[5] == 0.5 and decimals[7] == 16 and math.type(decimals[4]) == "float")
local texts = Expressions.texts()
assert(texts[2] == "é" and texts[3] == 'say "hi"' and texts[4] == "first\nsecond")
assert(Expressions.nothing() == nil)
assert(Expressions.logic(true, true, 0) == true, "both")
assert(Expressions.logic(false, true, 0) == false, "either, but they differ")
assert(Expressions.logic(false, false, 5) == true, "x > 3")
assert(Expressions.bits(5) == (5 & 15 | 5 ~ 3 | ~5 | 20))
assert(Expressions.conditional(-1, nil) == "negative nobody")
assert(Expressions.conditional(1, "Ann") == "positive Ann")
assert(Expressions.casts(-2.7, 3) == 1, "(int) -2.7 is -2")
assert(Expressions.arrays(4) == 4 + 2 + 6)
local limits = Expressions.limits()
assert(limits[1] == 2147483647 and limits[2] == -2147483648 and limits[4] == math.mininteger)
