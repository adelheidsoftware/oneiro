local Statements = require("src/statements")

assert(Statements.SQUARES[1] == 1 and Statements.SQUARES[3] == 9)
assert(Statements.locals(2) == 31)
assert(Statements.grade(95) == "A" and Statements.grade(60) == "B" and Statements.grade(10) == "C")
assert(Statements.firstPowerAbove(10) == 16)
assert(Statements.checked(5) == 5)
local ok, message = pcall(Statements.checked, -1)
assert(not ok and message:find("negative: -1", 1, true), "only the message survives")
ok, message = pcall(Statements.checked, 101)
assert(not ok and message:find("IllegalStateException", 1, true))
Statements.report("name", 3, 0.5, true)
assert(Statements.pick(true, nil, "b") == nil)
assert(Statements.pick(false, nil, "b") == "b")
assert(Statements.size(5, "s") == "s" and Statements.size(50, "s") == nil and Statements.size(500, "s") == "large")
assert(Statements.capped(12) == 10 and Statements.capped(3) == 3)
