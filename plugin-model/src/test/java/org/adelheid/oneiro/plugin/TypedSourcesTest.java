package org.adelheid.oneiro.plugin;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** The typed Resources and Urls classes. */
class TypedSourcesTest {

	@TempDir
	Path resources;

	@Test
	void resourcesFollowTheFolders() throws IOException {
		Files.createDirectories(resources.resolve("icons"));
		Files.writeString(resources.resolve("icons/herb.png"), "");
		Files.writeString(resources.resolve("icons/herb-dark.png"), "");
		Files.writeString(resources.resolve("ding.ogg"), "");
		Files.writeString(resources.resolve("notes.txt"), "");
		List<String> problems = new ArrayList<>();
		String source = TypedSources.resources("com.example.herbs", resources, problems);
		assertEquals(List.of("resources/notes.txt is not a PNG image or an Ogg sound, the only resources the client"
				+ " loads."), problems);
		assertEquals("""
				// Generated by Oneiro from the plugin's resources folder; it changes when they do.
				package com.example.herbs;

				import org.adelheid.oneiro.api.LuaGlobal;
				import org.adelheid.oneiro.api.LuaName;
				import org.adelheid.oneiro.rs3.PluginAudioResource;
				import org.adelheid.oneiro.rs3.PluginImageResource;

				/**
				 * The plugin's resources, the files under {@code src/main/resources/} that the client loads.
				 *
				 * <p>Lua: {@code Plugin.resources}
				 */
				@LuaGlobal("Plugin.resources")
				public final class Resources {

					private Resources() {
					}

					/** {@code resources/ding.ogg}: {@code Plugin.resources.ding} */
					public static final PluginAudioResource ding = lua();

					/** The files under {@code resources/icons/}: {@code Plugin.resources.icons} */
					@LuaGlobal("Plugin.resources.icons")
					public static final class icons {

						private icons() {
						}

						/** {@code resources/icons/herb.png}: {@code Plugin.resources.icons.herb} */
						public static final PluginImageResource herb = lua();

						/** {@code resources/icons/herb-dark.png}: {@code Plugin.resources.icons["herb-dark"]} */
						@LuaName("herb-dark")
						public static final PluginImageResource herb_dark = lua();
					}

					private static <T> T lua() {
						throw new UnsupportedOperationException("Resources exist only in Lua; Oneiro compiles what uses them.");
					}
				}
				""", source);
	}

	@Test
	void noResourcesNoClass() throws IOException {
		assertNull(TypedSources.resources("com.example", resources.resolve("absent"), new ArrayList<>()));
	}

	@Test
	void urlsByAlias() {
		String source = TypedSources.urls("com.example.herbs", Map.of("prices", "https://prices.example.org"));
		assertTrue(source != null && source.contains("""
					/** {@code https://prices.example.org}: {@code Plugin.urls.prices} */
					public static final String prices = lua();
				"""), source);
		assertNull(TypedSources.urls("com.example.herbs", Map.of()));
	}
}
