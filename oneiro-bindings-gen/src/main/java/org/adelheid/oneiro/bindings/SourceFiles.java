package org.adelheid.oneiro.bindings;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import org.adelheid.oneiro.bindings.JavaBindings.Form;
import org.adelheid.oneiro.bindings.JavaBindings.Node;

/**
 * The parts of the bindings' source files that do not come from one table: the header and imports every file starts
 * with, the whole of {@code package-info.java} and {@code LuaOnly}, the callback interfaces, and for the RS3 API, the
 * event subscription types and {@code Globals}.
 */
final class SourceFiles {

	private static final List<String> ANNOTATION_IMPORTS = List.of("org.adelheid.oneiro.api.LuaColon",
			"org.adelheid.oneiro.api.LuaCopy", "org.adelheid.oneiro.api.LuaDevOnly", "org.adelheid.oneiro.api.LuaDot",
			"org.adelheid.oneiro.api.LuaEvent", "org.adelheid.oneiro.api.LuaFromId",
			"org.adelheid.oneiro.api.LuaGlobal", "org.adelheid.oneiro.api.LuaIndex",
			"org.adelheid.oneiro.api.LuaManifestFlag", "org.adelheid.oneiro.api.LuaName",
			"org.adelheid.oneiro.api.LuaOperator", "org.adelheid.oneiro.api.LuaSame",
			"org.adelheid.oneiro.api.LuaPermission", "org.adelheid.oneiro.api.LuaReturnValues",
			"org.adelheid.oneiro.api.LuaReview", "org.adelheid.oneiro.api.LuaType",
			"org.jspecify.annotations.Nullable");
	/**
	 * The JDK types the bindings use, which the generator names fully until {@link #file} imports them, a nullable one
	 * with JSpecify's annotation before its simple name: {@code java.util.function.@Nullable Consumer}.
	 */
	private static final Pattern JDK_TYPE =
			Pattern.compile("\\b(java\\.util\\.(?:function\\.)?)(?:@Nullable )?([A-Z]\\w*)");
	/** Where a qualified name starts: after no name or dot, so that {@code a.b.} is not found inside {@code x.a.b.}. */
	private static final String NOT_AFTER_NAME = "(?<![\\w.])";
	/** The declaration of a file's top-level class or interface, after its Javadoc and annotations. */
	private static final Pattern TOP_LEVEL_CLASS = Pattern.compile("^public ", Pattern.MULTILINE);

	/** The documentation of the RS3 bindings' package. */
	private static final String RS3_PACKAGE_DOC = """
			/**
			 * The RS3 Client Plugin API as Oneiro's Java bindings: one class per Lua table, so that the Java
			 * reads like the Lua it becomes. Generated by Oneiro's bindings generator from rs3-api-types on this
			 * machine.
			 */
			""";

	private final JavaBindings bindings;
	private final ApiModel model;

	SourceFiles(JavaBindings bindings) {
		this.bindings = bindings;
		this.model = bindings.model;
	}

	/**
	 * A source file: the header, the imports, and the classes. The classes name the JDK's types fully, and the classes
	 * of other bindings, such as the RS3 API's {@code ui.Component} in a library's, and of the plugin's own Lua in
	 * other packages, which keeps the generator simple; here each becomes an import and its simple name, or within the
	 * file's package its simple name alone. The exception is a name that a class nested in the file takes, such as
	 * {@code ui.List}, or that a class of the package or an earlier import takes, where only the qualified name reaches
	 * the type.
	 */
	String file(String classes, Set<String> shadowed, String packageName) {
		BindingsTarget target = bindings.target;
		Set<String> imports = new TreeSet<>(ANNOTATION_IMPORTS);
		if (!target.isRs3()) {
			imports.add("org.adelheid.oneiro.api.LuaModule");
		}
		if (target.isPlugin()) {
			imports.add("org.jspecify.annotations.NullMarked");
		}
		if (target.optional()) {
			imports.add("org.adelheid.oneiro.api.LuaOptional");
		}
		Set<String> taken = new HashSet<>(shadowed);
		String body = classes;
		Matcher qualified = JDK_TYPE.matcher(classes);
		Set<String> found = new TreeSet<>();
		while (qualified.find()) {
			found.add(qualified.group(1) + qualified.group(2));
		}
		for (String name : found) {
			int dot = name.lastIndexOf('.');
			String simple = name.substring(dot + 1);
			if (!shadowed.contains(simple)) {
				imports.add(name);
				taken.add(simple);
				String packagePrefix = Pattern.quote(name.substring(0, dot + 1));
				body = body.replaceAll("\\b" + packagePrefix + "(@Nullable )?" + simple + "\\b", "$1" + simple);
			}
		}
		Set<String> samePackage = bindings.topNamesByPackage().getOrDefault(packageName, Set.of());
		taken.addAll(samePackage);
		List<JavaBindings> named = new ArrayList<>(bindings.foreign);
		if (target.isPlugin()) {
			named.addFirst(bindings);
		}
		for (JavaBindings other : named) {
			for (Map.Entry<String, Set<String>> entry : other.topNamesByPackage().entrySet()) {
				String prefix = entry.getKey() + ".";
				Matcher qualifiedType = Pattern.compile(NOT_AFTER_NAME + Pattern.quote(prefix)
						+ "(?:@Nullable )?([A-Za-z_]\\w*)").matcher(body);
				Set<String> tops = new TreeSet<>();
				while (qualifiedType.find()) {
					// A package's subpackage is no class of it: <root>.core.Levels is not a class core of <root>
					if (entry.getValue().contains(qualifiedType.group(1))) {
						tops.add(qualifiedType.group(1));
					}
				}
				boolean ownPackage = other == bindings && entry.getKey().equals(packageName);
				for (String top : tops) {
					if (ownPackage ? !shadowed.contains(top) : taken.add(top)) {
						if (!ownPackage) {
							imports.add(prefix + top);
						}
						body = body.replaceAll(NOT_AFTER_NAME + Pattern.quote(prefix) + "(@Nullable )?"
								+ Pattern.quote(top) + "\\b", "$1" + top);
					}
				}
			}
		}
		if (target.isPlugin()) {
			// The plugin's packages are its own, so each class is marked rather than the package
			body = TOP_LEVEL_CLASS.matcher(body).replaceFirst("@NullMarked\n$0");
		}
		StringBuilder header = new StringBuilder("// Generated by Oneiro's bindings generator from " + target.origin()
				+ " on this machine; not for distribution.\npackage " + packageName + ";\n\n");
		imports.forEach(name -> header.append("import ").append(name).append(";\n"));
		return header.append("\n").append(body).toString();
	}

	/** The simple names of the classes nested in a top-level class, at any depth. */
	static Set<String> nestedNames(Node node) {
		Set<String> names = new HashSet<>();
		for (Node child : node.children.values()) {
			names.add(child.javaName);
			names.addAll(nestedNames(child));
		}
		return names;
	}

	String packageInfo() {
		BindingsTarget target = bindings.target;
		String doc = target.isRs3() ? RS3_PACKAGE_DOC : """
				/**
				 * The Lua library %s as Oneiro's Java bindings: one class per Lua table, so that the Java reads like
				 * the Lua it becomes. Generated by Oneiro's bindings generator from its LuaCATS types on this machine.
				 */
				""".formatted(target.library());
		return doc + "@NullMarked\npackage " + target.packageName()
				+ ";\n\nimport org.jspecify.annotations.NullMarked;\n";
	}

	String luaOnly(String packageName) {
		BindingsTarget target = bindings.target;
		return """
				// Generated by Oneiro's bindings generator; not for distribution.
				package %s;

				/** Bindings stand for Lua that %s provides; none of them runs on the JVM. */
				final class LuaOnly {

					private LuaOnly() {
					}

					/** The value of a binding field, which exists only in Lua. */
					static <T> T value() {
						throw error();
					}

					static UnsupportedOperationException error() {
						return new UnsupportedOperationException("%s exist only in Lua; Oneiro compiles"
								+ " calls to them, they never run on the JVM.");
					}
				}
				""".formatted(packageName, target.provider(), switch (target.kind()) {
					case RS3 -> "RS3 bindings";
					case LIBRARY, DEPENDENCY -> "The bindings of " + target.library();
					case PLUGIN -> "The bindings of the plugin's Lua";
				});
	}

	/**
	 * {@code Function3<T1, T2, T3, R>} or {@code Consumer3<T1, T2, T3>}: a Lua function of more values than the
	 * interfaces of {@code java.util.function} take, which a lambda implements as it implements those.
	 */
	String callback(String name) {
		boolean returns = name.startsWith("Function");
		int count = Integer.parseInt(name.substring("Function".length()));
		List<String> variables = new ArrayList<>();
		List<String> parameters = new ArrayList<>();
		for (int index = 1; index <= count; index++) {
			variables.add("T" + index);
			parameters.add("T" + index + " value" + index);
		}
		StringBuilder out = new StringBuilder();
		List<String> doc = new ArrayList<>();
		doc.add("A Lua function that takes " + count + " values and returns " + (returns ? "one" : "nothing")
				+ ", for a callback of more values than the interfaces of {@code java.util.function} take.");
		doc.add("");
		variables.forEach(variable -> doc.add("@param <" + variable + "> the type of value " + variable.substring(1)));
		if (returns) {
			doc.add("@param <R> the type of what it returns");
			variables.add("R");
		}
		JavaText.javadoc(out, "", doc);
		out.append("@FunctionalInterface\n");
		out.append("public interface ").append(name).append("<").append(String.join(", ", variables)).append("> {\n\n");
		String arguments = parameters.stream()
				.map(parameter -> parameter.substring(parameter.indexOf(' ') + 1))
				.collect(Collectors.joining(", "));
		JavaText.javadoc(out, "\t", List.of("Calls the function.", "", "<p>Lua: {@code fn(" + arguments + ")}"));
		out.append("\t").append(returns ? "R apply(" : "void accept(").append(String.join(", ", parameters))
				.append(");\n}\n");
		return file(out.toString(), Set.of(), bindings.target.packageName());
	}

	String subscription(boolean predicate) {
		String name = predicate ? "EventPredicateSubscription" : "EventSubscription";
		String callback = predicate ? "java.util.function.Predicate<T>" : "java.util.function.Consumer<T>";
		ApiModel.ClassDef stub = model.classes.get("EventSubscription");
		List<String> doc = new ArrayList<>(stub == null ? List.of() : JavaText.lines(stub.description));
		doc.add(predicate
				? "<p>The callbacks of this event return a boolean that the client acts on."
				: "<p>The callbacks of this event return nothing.");
		doc.add("<p>Lua: {@code Event.Name.Subscribe(name, callback)}; a plugin class's {@code @Subscribe} methods are"
				+ " subscribed this way.");
		doc.add("@param <T> the event's payload class");
		StringBuilder out = new StringBuilder();
		JavaText.javadoc(out, "", doc);
		out.append("@LuaType(\"EventSubscription\")\n");
		out.append("public final class ").append(name).append("<T> {\n\n");
		out.append("\tprivate ").append(name).append("() {\n\t\tthrow LuaOnly.error();\n\t}\n\n");
		JavaText.javadoc(out, "\t", List.of(
				"Subscribes the callback under the name, replacing what this plugin subscribed under it to this"
						+ " event before.",
				"",
				"<p>Lua: {@code Event.Name.Subscribe(name, callback)}",
				"@param name the subscription's name, such as {@code \"my-plugin.tick\"}",
				"@param callback called with the event's payload"));
		out.append("\t@LuaDot\n\tpublic native void Subscribe(String name, ").append(callback)
				.append(" callback);\n\n");
		JavaText.javadoc(out, "\t", List.of(
				"Removes this plugin's subscription under the name.",
				"",
				"<p>Lua: {@code Event.Name.Unsubscribe(name)}",
				"@param name the name it was subscribed under"));
		out.append("\t@LuaDot\n\tpublic native void Unsubscribe(String name);\n}\n");
		return file(out.toString(), Set.of(), bindings.target.packageName());
	}

	/** The global functions, {@code print}, {@code log}, {@code formatStr} and the rest, as static methods. */
	String globals() {
		StringBuilder out = new StringBuilder();
		JavaText.javadoc(out, "", List.of(
				"The Lua globals that are functions: {@code Globals.log(text)} is {@code log(text)}.",
				"Import them statically to write {@code log(text)} in Java too.",
				"",
				"<p>Lua: the global functions."));
		out.append("@LuaGlobal(\"\")\npublic final class Globals {\n\n");
		out.append("\tprivate Globals() {\n\t\tthrow LuaOnly.error();\n\t}\n");
		Set<String> signatures = new HashSet<>();
		for (ApiModel.FunctionDef function : model.globalFunctions) {
			if (bindings.overrides.has("skip", function.name())) {
				continue;
			}
			String javaName = JavaText.javaIdentifier(function.name());
			for (Form form : bindings.memberBindings().forms("", function)) {
				if (!signatures.add(javaName + "(" + MemberBindings.erased(form.params()) + ")")) {
					continue;
				}
				out.append("\n");
				List<String> doc = new ArrayList<>(JavaText.lines(function.description()));
				doc.add("<p>Lua: {@code " + function.name() + "("
						+ MemberBindings.luaArguments(form.params(), function.varargs()) + ")}");
				MemberBindings.paramDocs(doc, form.params());
				JavaText.javadoc(out, "\t", doc);
				bindings.memberAnnotations(out, function.name(), "\t");
				out.append("\tpublic static native ").append(form.returned().text()).append(" ").append(javaName)
						.append("(").append(MemberBindings.parameterList(form.params(), function.varargs()))
						.append(");\n");
			}
		}
		out.append("}\n");
		return file(out.toString(), Set.of(), bindings.target.packageName());
	}
}
